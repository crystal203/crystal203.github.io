import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {actionModules} from '../../gtfx/action-modules.js';
import {equipmentProfile,preferredWeaponSelection,sourceExclusiveWeapon,shieldAllowedForWeapon} from '../../gtfx/equipment-selection.js';
import {materialBlend} from '../../gtfx/material-blend.js';
const read=name=>JSON.parse(readFileSync(new URL('../../gtfx/assets/'+name,import.meta.url),'utf8'));
const native=read('native-characters/tanker.json'),index=read('characters/tanker.json'),catalog=read('weapon-types.json'),hero=native.profile.appearances[0];
assert.equal(hero,'tanker_2');
const weapon=preferredWeaponSelection(native,native.profile,hero),profile=equipmentProfile(native,native.profile,hero,hero,weapon,catalog),exclusiveWeapon=sourceExclusiveWeapon(native,profile,hero,hero,weapon);
const options={appearance:hero,heroAppearance:hero,weapon,profile,exclusiveWeapon,weaponEquipped:true,shield:shieldAllowedForWeapon(native,profile,hero)?profile.shield||'':'',direction:'right',targetDistance:6};
const support=actionModules('tanker',index,options,native,{tanker:native.plans}).find(module=>module.id==='support');
const action=native.actions['BasicSupport:Tanker'],requested=action.PresetInfo.find(row=>row.buff).buff;
const buff=support.tracks.find(track=>track.effect.preset===requested);
assert(buff,'support must use the exact requested pool preset, before any AssetName alias');
assert.equal(buff.effect,index.effects.find(effect=>effect.preset===requested));
const beam=buff.effect.statics.find(item=>item.name==='Trans_mesh').material;
assert.equal(beam.shader,'Effect/Mask_Additive_Tint');
assert.deepEqual(beam.nativeBlend,[5,1]);
assert.equal(materialBlend(beam).additive,true);
assert(buff.effect.sourceBundle,'the selected consumer must retain its native source provenance');
console.log(JSON.stringify({character:'tanker',hero,action:action.Name,requested,actual:buff.effect.preset,sourceBundle:buff.effect.sourceBundle,shader:beam.shader,nativeBlend:beam.nativeBlend,tracks:support.tracks.map(track=>track.effect.preset)}));
