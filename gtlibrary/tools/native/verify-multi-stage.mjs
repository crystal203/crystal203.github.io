import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {fresh,restore,saveKey} from '../../gtonline/progress.js';
import {hasCapability} from '../../gtonline/loadout.js';
import {InnGame} from '../../gtonline/stages/inn.js';
import {ForestEntranceGame} from '../../gtonline/stages/forest-entrance.js';
import {restoreInn} from '../../gtonline/stages/inn-progress.js';
const stage=id=>readFile(new URL('../../gtonline/assets/stage-'+id+'.json',import.meta.url),'utf8').then(JSON.parse);
const [inn,forest]=await Promise.all([stage('1-1'),stage('1-2')]);
const state=fresh(inn,[30017,30017,123]);
assert.deepEqual(state.loadout,[30017]);assert.ok(hasCapability(state,'gloves'));
assert.deepEqual(state.flags,[]);assert.deepEqual(state.collected,[],'carrying grants no treasure or story progress');
assert.notEqual(saveKey(inn),saveKey(forest));assert.equal(saveKey(inn),'gtonline.1-1.v1');
assert.equal(restore(forest,state),null);assert.equal(restore(inn,{...state,stageId:'1-2'}),null);
assert.ok(!hasCapability(fresh(forest),'gloves'),'new stage does not inherit another stage capability');
assert.ok(hasCapability(restore(inn,JSON.stringify(state)),'gloves'),'carried item survives reload');
const old={...fresh(inn),flags:['opening','section_5'],loadout:undefined,stageId:undefined};
assert.deepEqual(restoreInn(inn,JSON.stringify(old)).party.map(p=>p.handle),['leader','maiden']);
const unversioned={...fresh(inn),flags:['opening','lorraine_contact']};
assert.ok(restoreInn(inn,unversioned).flags.includes('maiden_enter:maiden_1'),'unversioned legacy story must still migrate');
assert.deepEqual(restore(forest,{...fresh(forest),flags:['section_5']}).party.map(p=>p.handle),['leader'],'generic restore never creates Lorraine');
const storage=new Map();const runtime={events:{stop(){}},frameListeners:new Set(),getWorldRecords(){return [];},clearWorldSpeech(){}};
for(const [Stage,definition] of [[InnGame,inn],[ForestEntranceGame,forest]]){
 const g=new Stage(runtime,{...definition,objects:[]},{storage:{setItem:(k,v)=>storage.set(k,v)},loadout:[30017]});g.mode='play';g.save();g.dispose();
}
assert.equal(storage.size,2);assert.equal(runtime.frameListeners.size,0);
const bf=forest.scenes.butterfly_1,move=bf.commands.find(c=>c.op==='move');
assert.deepEqual(move.points,forest.nativeEvents.ButterflyGuide.data.butterfly_1[0].$butterfly.move.to);
assert.equal(move.at,0);assert.equal(bf.blocking,false);
const second=forest.scenes.butterfly_2;assert.equal(second.commands.at(-1).op,'visible');assert.equal(second.commands.at(-1).value,false);
assert.equal(forest.audit.storyParityCertified,false,'incomplete plot must never be certified by static tests');
const engine=await readFile(new URL('../../gtonline/game.js',import.meta.url),'utf8');
assert.ok(!/section_4|trio_|dragon_|maiden|ForestEntrance|1-1|1-2|RopeSway/.test(engine),'shared engine must not contain stage identities or story algorithms');
console.log('PASS loadout grants/persistence, legacy 1-1 migration, cross-stage save isolation, lifecycle disposal, native butterfly route and incomplete-story certification guard.');
